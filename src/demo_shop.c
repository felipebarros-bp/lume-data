/*
 * The e-commerce demo database ("Shop Demo (e-commerce)", in-memory SQLite): a small online store
 * with categories, products, customers, orders, order items, payments, shipments and reviews.
 * Everything is generated deterministically from the row numbers (no randomness), relative to
 * today, so reports always show the last two years. Names and cities are fictitious.
 */
#include "demo_shop.h"

const char *demo_shop_sql =
    "PRAGMA foreign_keys = ON;"
    "CREATE TABLE categories(id INTEGER PRIMARY KEY, name TEXT NOT NULL, parent_id INTEGER REFERENCES categories(id));"
    "INSERT INTO categories VALUES (1,'Electronics',NULL),(2,'Phones',1),(3,'Computers',1),(4,'Home',NULL),(5,'Kitchen',4),"
    "  (6,'Fashion',NULL),(7,'Shoes',6),(8,'Sports',NULL),(9,'Books',NULL),(10,'Beauty',NULL);"

    "CREATE TABLE products(id INTEGER PRIMARY KEY, sku TEXT NOT NULL UNIQUE, name TEXT NOT NULL,"
    "  category_id INTEGER NOT NULL REFERENCES categories(id), price REAL NOT NULL, cost REAL NOT NULL,"
    "  active INTEGER NOT NULL DEFAULT 1, created_at TEXT NOT NULL);"
    "CREATE TEMP TABLE pbase(id INTEGER PRIMARY KEY, category_id INTEGER, name TEXT, price REAL);"
    "INSERT INTO pbase(category_id, name, price) VALUES"
    "  (2,'Smartphone Nova',1899),(2,'Smartphone Lite',999),(2,'Wireless Earbuds',249),(2,'Phone Case',59),"
    "  (3,'Notebook Air',4299),(3,'Mechanical Keyboard',389),(3,'Wireless Mouse',129),(3,'27in Monitor',1399),"
    "  (5,'Air Fryer',499),(5,'Coffee Maker',329),(5,'Blender',219),(5,'Knife Set',179),"
    "  (7,'Running Shoes',449),(7,'Sneakers',299),(7,'Sandals',119),(7,'Boots',529),"
    "  (8,'Yoga Mat',99),(8,'Dumbbell Set',349),(8,'Bike Helmet',259),(8,'Water Bottle',49),"
    "  (9,'SQL Handbook',89),(9,'Data Storytelling',75),(9,'Cookbook',69),(9,'Novel',45),"
    "  (10,'Face Cream',119),(10,'Perfume',389),(10,'Shampoo',39),(10,'Hair Dryer',279);"
    "INSERT INTO products(sku, name, category_id, price, cost, active, created_at)"
    "  SELECT printf('SKU-%04d', (b.id - 1) * 3 + v.k), b.name || CASE v.k WHEN 1 THEN '' WHEN 2 THEN ' Pro' ELSE ' Plus' END,"
    "    b.category_id, round(b.price * (1 + (v.k - 1) * 0.25), 2), round(b.price * (1 + (v.k - 1) * 0.25) * (0.52 + (b.id % 5) * 0.04), 2),"
    "    CASE WHEN (b.id * 3 + v.k) % 29 = 0 THEN 0 ELSE 1 END, date('now', '-' || (700 + b.id * 3 + v.k) || ' days')"
    "  FROM pbase b, (SELECT 1 AS k UNION ALL SELECT 2 UNION ALL SELECT 3) v ORDER BY b.id, v.k;"

    "CREATE TABLE customers(id INTEGER PRIMARY KEY, name TEXT NOT NULL, email TEXT NOT NULL, city TEXT NOT NULL,"
    "  state TEXT NOT NULL, segment TEXT NOT NULL, created_at TEXT NOT NULL);"
    "CREATE TEMP TABLE fnames(i INTEGER PRIMARY KEY, v TEXT);"
    "INSERT INTO fnames(v) VALUES ('Ana'),('Bruno'),('Carla'),('Diego'),('Elisa'),('Fabio'),('Gabriela'),('Heitor'),('Isabela'),('Joao'),"
    "  ('Julia'),('Lucas'),('Mariana'),('Nicolas'),('Olivia'),('Pedro'),('Rafaela'),('Samuel'),('Tatiana'),('Vitor'),('Yasmin'),('Caio'),('Luana'),('Mateus');"
    "CREATE TEMP TABLE lnames(i INTEGER PRIMARY KEY, v TEXT);"
    "INSERT INTO lnames(v) VALUES ('Silva'),('Souza'),('Oliveira'),('Santos'),('Lima'),('Costa'),('Pereira'),('Almeida'),"
    "  ('Ribeiro'),('Carvalho'),('Gomes'),('Martins'),('Rocha'),('Barbosa'),('Freire'),('Teixeira');"
    "CREATE TEMP TABLE cities(i INTEGER PRIMARY KEY, city TEXT, state TEXT);"
    "INSERT INTO cities(city, state) VALUES ('Sao Paulo','SP'),('Rio de Janeiro','RJ'),('Belo Horizonte','MG'),('Salvador','BA'),"
    "  ('Recife','PE'),('Fortaleza','CE'),('Curitiba','PR'),('Porto Alegre','RS'),('Brasilia','DF'),('Campina Grande','PB'),"
    "  ('Manaus','AM'),('Goiania','GO'),('Florianopolis','SC'),('Belem','PA'),('Natal','RN'),('Campinas','SP');"
    "WITH RECURSIVE n(i) AS (SELECT 1 UNION ALL SELECT i + 1 FROM n WHERE i < 400)"
    "  INSERT INTO customers(id, name, email, city, state, segment, created_at)"
    "  SELECT n.i, f.v || ' ' || l.v, lower(f.v) || '.' || lower(l.v) || n.i || '@example.com', c.city, c.state,"
    "    CASE WHEN n.i % 10 = 0 THEN 'business' WHEN n.i % 4 = 0 THEN 'premium' ELSE 'consumer' END,"
    "    date('now', '-' || (30 + (n.i * 37) % 700) || ' days')"
    "  FROM n JOIN fnames f ON f.i = 1 + (n.i * 7) % 24 JOIN lnames l ON l.i = 1 + (n.i * 11) % 16"
    "  JOIN cities c ON c.i = 1 + CASE WHEN n.i % 3 = 0 THEN 0 ELSE (n.i * 5) % 16 END;"

    "CREATE TABLE orders(id INTEGER PRIMARY KEY, customer_id INTEGER NOT NULL REFERENCES customers(id), order_date TEXT NOT NULL,"
    "  status TEXT NOT NULL, channel TEXT NOT NULL, coupon_code TEXT, subtotal REAL NOT NULL DEFAULT 0,"
    "  discount REAL NOT NULL DEFAULT 0, shipping_fee REAL NOT NULL DEFAULT 0, total REAL NOT NULL DEFAULT 0);"
    "WITH RECURSIVE n(i) AS (SELECT 1 UNION ALL SELECT i + 1 FROM n WHERE i < 4000)"
    "  INSERT INTO orders(id, customer_id, order_date, status, channel, coupon_code)"
    "  SELECT i, 1 + (i * 7919) % 400,"
    /* growth: half of the orders spread evenly over two years, half denser towards today */
    "    date('now', '-' || CASE WHEN i % 2 = 0 THEN (i * 131) % 730 ELSE ((i * 131) % 730 + ((i * 131) % 730) * ((i * 131) % 730) / 730) / 2 END || ' days'),"
    "    CASE WHEN (i * 13) % 100 < 68 THEN 'delivered' WHEN (i * 13) % 100 < 78 THEN 'shipped' WHEN (i * 13) % 100 < 86 THEN 'paid'"
    "         WHEN (i * 13) % 100 < 94 THEN 'cancelled' ELSE 'returned' END,"
    "    CASE WHEN i % 10 < 5 THEN 'web' WHEN i % 10 < 8 THEN 'app' ELSE 'marketplace' END,"
    "    CASE WHEN i % 9 = 0 THEN 'WELCOME10' WHEN i % 23 = 0 THEN 'BLACKFRIDAY' END"
    "  FROM n;"
    /* seasonality: one order in six moves to Black Friday week or the Christmas run-up of its year (never into the future) */
    "UPDATE orders SET order_date = strftime('%Y', order_date) || CASE WHEN (id / 6) % 2 = 0 THEN '-11-' || printf('%02d', 20 + id % 10) ELSE '-12-' || printf('%02d', 1 + id % 22) END"
    "  WHERE id % 6 = 0 AND strftime('%Y', order_date) || CASE WHEN (id / 6) % 2 = 0 THEN '-11-' || printf('%02d', 20 + id % 10) ELSE '-12-' || printf('%02d', 1 + id % 22) END <= date('now');"

    "CREATE TABLE order_items(id INTEGER PRIMARY KEY, order_id INTEGER NOT NULL REFERENCES orders(id),"
    "  product_id INTEGER NOT NULL REFERENCES products(id), quantity INTEGER NOT NULL, unit_price REAL NOT NULL);"
    "INSERT INTO order_items(order_id, product_id, quantity, unit_price)"
    "  SELECT o.id, p.id, 1 + (o.id + k.k) % 3, p.price"
    "  FROM orders o JOIN (SELECT 1 AS k UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4) k ON k.k <= 1 + o.id % 4"
    "  JOIN products p ON p.id = 1 + (o.id * 31 + k.k * 17) % 84"
    "  ORDER BY o.id, k.k;"
    "UPDATE orders SET subtotal = (SELECT round(sum(quantity * unit_price), 2) FROM order_items WHERE order_id = orders.id);"
    "UPDATE orders SET discount = round(CASE coupon_code WHEN 'WELCOME10' THEN subtotal * 0.10 WHEN 'BLACKFRIDAY' THEN subtotal * 0.20 ELSE 0 END, 2),"
    "  shipping_fee = CASE WHEN subtotal >= 299 THEN 0 ELSE 19.90 END;"
    "UPDATE orders SET total = round(subtotal - discount + shipping_fee, 2);"

    "CREATE TABLE payments(id INTEGER PRIMARY KEY, order_id INTEGER NOT NULL REFERENCES orders(id), method TEXT NOT NULL,"
    "  installments INTEGER NOT NULL, amount REAL NOT NULL, status TEXT NOT NULL, paid_at TEXT);"
    "INSERT INTO payments(order_id, method, installments, amount, status, paid_at)"
    "  SELECT id, CASE WHEN id % 10 < 5 THEN 'pix' WHEN id % 10 < 9 THEN 'credit_card' ELSE 'boleto' END,"
    "    CASE WHEN id % 10 BETWEEN 5 AND 8 THEN 1 + id % 10 ELSE 1 END, total,"
    "    CASE status WHEN 'cancelled' THEN 'refunded' WHEN 'returned' THEN 'refunded' ELSE 'approved' END,"
    "    CASE WHEN id % 10 = 9 THEN date(order_date, '+2 days') ELSE order_date END"
    "  FROM orders;"

    "CREATE TABLE shipments(id INTEGER PRIMARY KEY, order_id INTEGER NOT NULL REFERENCES orders(id), carrier TEXT NOT NULL,"
    "  shipped_at TEXT NOT NULL, delivered_at TEXT, freight_cost REAL NOT NULL, destination_state TEXT NOT NULL);"
    "INSERT INTO shipments(order_id, carrier, shipped_at, delivered_at, freight_cost, destination_state)"
    "  SELECT o.id, CASE o.id % 4 WHEN 0 THEN 'Correios' WHEN 1 THEN 'Jadlog' WHEN 2 THEN 'Loggi' ELSE 'Total Express' END,"
    "    date(o.order_date, '+' || (1 + o.id % 3) || ' days'),"
    "    CASE WHEN o.status IN ('delivered','returned') THEN date(o.order_date, '+' || (3 + o.id % 3 + (o.id * 7) % 9) || ' days') END,"
    "    round(8 + (o.id % 25) * 0.9 + CASE WHEN c.state IN ('AM','PA') THEN 18 WHEN c.state IN ('SP','RJ','MG') THEN 0 ELSE 7 END, 2), c.state"
    "  FROM orders o JOIN customers c ON c.id = o.customer_id WHERE o.status IN ('shipped','delivered','returned');"

    "CREATE TABLE reviews(id INTEGER PRIMARY KEY, order_id INTEGER NOT NULL REFERENCES orders(id),"
    "  product_id INTEGER NOT NULL REFERENCES products(id), rating INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5), created_at TEXT NOT NULL);"
    "INSERT INTO reviews(order_id, product_id, rating, created_at)"
    "  SELECT o.id, (SELECT product_id FROM order_items WHERE order_id = o.id ORDER BY id LIMIT 1),"
    "    CASE WHEN o.id % 11 = 0 THEN 1 WHEN o.id % 7 = 0 THEN 3 WHEN o.id % 5 = 0 THEN 4 ELSE 5 END,"
    "    s.delivered_at"
    "  FROM orders o JOIN shipments s ON s.order_id = o.id WHERE o.status = 'delivered' AND o.id % 3 = 0;"

    "CREATE VIEW v_daily_sales AS SELECT order_date, count(*) AS orders, round(sum(total), 2) AS revenue"
    "  FROM orders WHERE status NOT IN ('cancelled','returned') GROUP BY order_date;"
    "CREATE INDEX ix_orders_date ON orders(order_date);"
    "CREATE INDEX ix_orders_customer ON orders(customer_id);"
    "CREATE INDEX ix_items_order ON order_items(order_id);"
    "CREATE INDEX ix_items_product ON order_items(product_id);"
    "DROP TABLE pbase; DROP TABLE fnames; DROP TABLE lnames; DROP TABLE cities;";
